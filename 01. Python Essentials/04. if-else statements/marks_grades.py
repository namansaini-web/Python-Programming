while True :
    marks = int(input("Enter your marks : "))
    
    if ( marks < 40 ) :
        print(" Your are fail")
    elif ( marks <= 59 ) :
        print(" Your grade is D ")

    elif ( marks <= 74) :
        print(" Your grade is C ")

    elif ( marks <= 89) :
        print(" Your grade is B ")

    else :
        print("Your grade is A ")  
    

